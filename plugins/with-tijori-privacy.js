/**
 * Locks down the Android build so Tijori's "nothing leaves your phone" promise is
 * enforced by the platform, not just by our code:
 *
 * - Release builds have the INTERNET permission stripped, so the app physically
 *   cannot reach the network. Debug builds keep it because Metro needs it.
 * - Android cloud backup and device-to-device transfer are disabled, so the
 *   encrypted database is never copied off the phone by the OS.
 */
const fs = require('fs');
const path = require('path');
const { withAndroidManifest, withDangerousMod } = require('expo/config-plugins');

const RELEASE_MANIFEST = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/with-tijori-privacy.js — do not edit. -->
<manifest xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:tools="http://schemas.android.com/tools">
    <uses-permission android:name="android.permission.INTERNET" tools:node="remove" />
    <uses-permission android:name="android.permission.ACCESS_NETWORK_STATE" tools:node="remove" />
    <uses-permission android:name="android.permission.SYSTEM_ALERT_WINDOW" tools:node="remove" />
</manifest>
`;

const EXTRACTION_RULES = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/with-tijori-privacy.js — do not edit. -->
<data-extraction-rules>
    <cloud-backup>
        <exclude domain="root" />
        <exclude domain="file" />
        <exclude domain="database" />
        <exclude domain="sharedpref" />
        <exclude domain="external" />
    </cloud-backup>
    <device-transfer>
        <exclude domain="root" />
        <exclude domain="file" />
        <exclude domain="database" />
        <exclude domain="sharedpref" />
        <exclude domain="external" />
    </device-transfer>
</data-extraction-rules>
`;

function withNoBackup(config) {
  return withAndroidManifest(config, (cfg) => {
    const application = cfg.modResults.manifest.application?.[0];
    if (application) {
      application.$['android:allowBackup'] = 'false';
      application.$['android:fullBackupContent'] = 'false';
      application.$['android:dataExtractionRules'] = '@xml/tijori_data_extraction_rules';
    }
    return cfg;
  });
}

function withGeneratedFiles(config) {
  return withDangerousMod(config, [
    'android',
    async (cfg) => {
      const appSrc = path.join(cfg.modRequest.platformProjectRoot, 'app', 'src');

      const releaseDir = path.join(appSrc, 'release');
      fs.mkdirSync(releaseDir, { recursive: true });
      fs.writeFileSync(path.join(releaseDir, 'AndroidManifest.xml'), RELEASE_MANIFEST);

      const xmlDir = path.join(appSrc, 'main', 'res', 'xml');
      fs.mkdirSync(xmlDir, { recursive: true });
      fs.writeFileSync(path.join(xmlDir, 'tijori_data_extraction_rules.xml'), EXTRACTION_RULES);

      return cfg;
    },
  ]);
}

module.exports = function withTijoriPrivacy(config) {
  return withGeneratedFiles(withNoBackup(config));
};
